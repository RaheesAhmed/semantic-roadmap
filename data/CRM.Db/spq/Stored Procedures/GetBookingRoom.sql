
CREATE PROCEDURE [spq].[GetBookingRoom] 
    @pRowID BIGINT
AS
    BEGIN
        SET NOCOUNT ON;	  	
		
        SELECT
            RowID ,
            wBookingRid ,
            wHotelBookingRid ,
            wRequestRid ,
            wHotelRid ,
            wHotelRoomRid ,
            wCounterRid ,
            wTravelAgencyRid ,
            wOrderNo ,
            wBedType ,
            wStartDate ,
            wEndtDate ,
            wDayOfStay ,
            wPaymentMethod ,
            wReceiptNo ,
            wVoucherNo ,
            wConfirmationNo ,
            wCashReceiptNo ,
            wCashTransferReceiptNo ,
            wGetKeyMethod ,
            wCurrCode ,
            wUseMemberCard ,
            wIncludeBreakfast ,
            wUseExtraAllotment ,
            wUseUpAllotment ,
            wTotalAmount ,
            wAdditionalFee ,
            wActualTotalAmount ,
            wTotalCost ,
            wRoomNo ,
            wGetKeyPasscode ,
            wHasStaffGetKey ,
            wHasClientGetKey ,
            wReGetKeyDate ,
            wSmsCount ,
            wIsConsigned ,
            wSameFloor ,
            wRoomExpenseState ,
            wCallCustomer ,
            wQuickCollectKey ,
            wIsCleaning ,
            wWarmReminderSMS ,
            wNoteRemark ,
            wIsConnectedRoom ,
            wIsSmoke,
            wIsExtraBed,
            wRemark ,
            wCheckoutRemarks ,
            wCrtDt ,
            wCrtBy ,
            wUpdDt ,
            wUpdBy ,
            wAllotmentGroupRid ,
            wRoomSMSSent ,
            wDisplayAgencyHotel ,
            wUseAgencyAllotment ,
            wStatus ,
            wSeqNo ,
            wBookingStatus ,
            wUnqualifiedRid,
            wOldBookingStatus = wBookingStatus -- Update时，Record获取与保存，DB的前后两次状态是否发生变化，如果发生变化，不能Save（可能预订已经被另外一个用户确认过，同时只能有一个用户可以做状态转换保存）
        FROM dbo.eBookingRoom
        WHERE @pRowID = RowID;                                                 
    END;